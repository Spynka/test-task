/* ----- парсинг + нормализация в E.164 -----
   Принимает:
     +37367188533
     0067..., 011... -> '+'
     37367188533 (код страны без '+')
     067188533 / 67188533 (национальный формат выбранной страны)
-------------------------------------------------- */
function parseAndNormalizePhone(rawInput, selectedCountry){
  if (!window.libphonenumber || typeof libphonenumber.parsePhoneNumber !== 'function') {
    return { ok:false, reason:'lib_missing' };
  }
  var s0 = (rawInput||'').trim();
  var s  = s0.replace(/[^\d+]/g,'');      // убираем всё, кроме + и цифр

  // 00/011 -> +
  if (s.indexOf('00') === 0) s = '+' + s.slice(2);
  if (s.indexOf('011') === 0) s = '+' + s.slice(3);

  var pn = null, route = '', cc = '';
  try {
    if (s[0] === '+') {
      route = 'plus';
      pn = libphonenumber.parsePhoneNumber(s);
    } else {
      try { cc = libphonenumber.getCountryCallingCode(selectedCountry); } catch(_) { cc=''; }
      if (cc && s.indexOf(String(cc)) === 0) {
        route = 'cc-no-plus';
        pn = libphonenumber.parsePhoneNumber('+'+s);
      } else {
        route = 'national';
        pn = libphonenumber.parsePhoneNumber(s, selectedCountry);
      }
    }
  } catch(e){
    return { ok:false, reason:'parse_exception', route: route };
  }

  if (!pn) return { ok:false, reason:'parse_null', route: route };

  var valid = (typeof pn.isValid === 'function') && pn.isValid();
var garbage = looksGarbage(pn.nationalNumber);
var countryMatch = !selectedCountry || !pn.country || String(pn.country).toUpperCase() === selectedCountry;

if (!valid || garbage || !countryMatch) {
    return { ok:false, reason:'reject', route: route, valid: valid, garbage: garbage, countryMatch: countryMatch };
}


  return { ok:true, e164: pn.number };
}

